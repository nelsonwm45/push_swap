#include "libft.h"

int	ft_atoi(const char *str)
{
	long	results;
	int		sign;

	results = 0;
	sign = 1;
	while ((*str >= 9 && *str <= 13) || *str == 32)
		str++;
	if (*str == '+')
		str++;
	else if (*str == '-')
	{
		sign *= -1;
		str++;
	}
	while (*str >= '0' && *str <= '9')
	{
		results *= 10;
		results += (*str - '0');
		str++;
	}
	return (sign * results);
}
