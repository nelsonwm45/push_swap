#include "libft.h"

char	*ft_strdup(const char *str)
{
	int		i;
	int		count;
	char	*dest;

	count = ft_strlen(str);
	dest = (char *)malloc(sizeof(char) * (count + 1));
	if (!dest)
		return (NULL);
	i = 0;
	while (str[i])
	{
		dest[i] = str[i];
		i++;
	}
	dest[i] = '\0';
	return (dest);
}
